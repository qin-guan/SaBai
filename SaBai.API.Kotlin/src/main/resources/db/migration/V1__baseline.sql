-- Schema for the tables this port maps, identical to what the C# EF Core migrations
-- create (same quoted PascalCase names, types, keys and indexes), so both APIs can run
-- against one database. On a database the C# API already migrated, Flyway baselines
-- at version 1 and skips this file.

CREATE TABLE "AspNetRoles" (
    "Id" uuid NOT NULL,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text,
    CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX "RoleNameIndex" ON "AspNetRoles" ("NormalizedName");

CREATE TABLE "StaffUsers" (
    "Id" uuid NOT NULL,
    "Nickname" character varying(255) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UserName" character varying(150),
    "NormalizedUserName" character varying(150),
    "Email" character varying(255),
    "NormalizedEmail" character varying(255),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    CONSTRAINT "PK_StaffUsers" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX "EmailIndex" ON "StaffUsers" ("NormalizedEmail");
CREATE UNIQUE INDEX "UserNameIndex" ON "StaffUsers" ("NormalizedUserName");

CREATE TABLE "AspNetUserRoles" (
    "UserId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_StaffUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "StaffUsers" ("Id") ON DELETE CASCADE
);
CREATE INDEX "IX_AspNetUserRoles_RoleId" ON "AspNetUserRoles" ("RoleId");

CREATE TABLE "AspNetUserTokens" (
    "UserId" uuid NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_StaffUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "StaffUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE "VillageCodes" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Code" character varying(255) NOT NULL,
    "Name" character varying(255) NOT NULL,
    "ColorHex" character varying(7) NOT NULL,
    "IsVisible" boolean NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_VillageCodes" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX "IX_VillageCodes_Code" ON "VillageCodes" ("Code");

CREATE TABLE "Patients" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "VillageCodeId" integer,
    "Name" character varying(255) NOT NULL,
    "IdentificationNumber" character varying(255),
    "ContactNo" character varying(255),
    "Gender" character varying(16) NOT NULL,
    "DateOfBirth" timestamp with time zone NOT NULL,
    "DrugAllergy" text NOT NULL,
    "HasPoorCard" boolean NOT NULL,
    "HasBS2Card" boolean NOT NULL,
    "HasSabaiCard" boolean NOT NULL,
    "ToGetReport" boolean NOT NULL,
    "PatientImagePublicId" text,
    "RekognitionFaceId" text,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Patients" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Patients_VillageCodes_VillageCodeId" FOREIGN KEY ("VillageCodeId") REFERENCES "VillageCodes" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_Patients_IdentificationNumber" ON "Patients" ("IdentificationNumber");
CREATE INDEX "IX_Patients_Name" ON "Patients" ("Name");
CREATE INDEX "IX_Patients_VillageCodeId" ON "Patients" ("VillageCodeId");

CREATE TABLE "Visits" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "PatientId" integer NOT NULL,
    "VillageCodeId" integer NOT NULL,
    "Date" timestamp with time zone NOT NULL,
    "Status" character varying(100) NOT NULL,
    CONSTRAINT "PK_Visits" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Visits_Patients_PatientId" FOREIGN KEY ("PatientId") REFERENCES "Patients" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Visits_VillageCodes_VillageCodeId" FOREIGN KEY ("VillageCodeId") REFERENCES "VillageCodes" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_Visits_Date" ON "Visits" ("Date");
CREATE INDEX "IX_Visits_PatientId" ON "Visits" ("PatientId");
CREATE INDEX "IX_Visits_VillageCodeId" ON "Visits" ("VillageCodeId");

CREATE TABLE "Vitals" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "VisitId" integer NOT NULL,
    "RecordedAt" timestamp with time zone,
    "Height" numeric(5,2),
    "Weight" numeric(5,2),
    "Temperature" numeric(4,2),
    "Systolic" integer,
    "Diastolic" integer,
    "HeartRate" integer,
    "HemocueCount" numeric(5,2),
    "DiabetesMellitus" boolean,
    "UrineTest" text,
    "BloodGlucoseNonFasting" numeric(5,2),
    "BloodGlucoseFasting" numeric(5,2),
    "Hba1c" numeric(5,2),
    "Others" text,
    CONSTRAINT "PK_Vitals" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Vitals_Visits_VisitId" FOREIGN KEY ("VisitId") REFERENCES "Visits" ("Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX "IX_Vitals_VisitId" ON "Vitals" ("VisitId");

CREATE TABLE "MedicationActiveIngredients" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Name" character varying(255) NOT NULL,
    "UnitOfMeasurement" character varying(255) NOT NULL,
    "FallBelow" integer NOT NULL,
    "Remarks" text,
    CONSTRAINT "PK_MedicationActiveIngredients" PRIMARY KEY ("Id")
);

CREATE TABLE "MedicationBrands" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Name" character varying(255) NOT NULL,
    "ActiveIngredientId" integer NOT NULL,
    "Remarks" text,
    CONSTRAINT "PK_MedicationBrands" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_MedicationBrands_MedicationActiveIngredients_ActiveIngredie~" FOREIGN KEY ("ActiveIngredientId") REFERENCES "MedicationActiveIngredients" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_MedicationBrands_ActiveIngredientId" ON "MedicationBrands" ("ActiveIngredientId");

CREATE TABLE "Consults" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Date" timestamp with time zone NOT NULL,
    "PastMedicalHistory" text,
    "Consultation" text,
    "TreatmentPlan" text,
    "ReferredFor" text,
    "ReferralNotes" text,
    "Remarks" text,
    "DoctorId" uuid NOT NULL,
    "VisitId" integer NOT NULL,
    CONSTRAINT "PK_Consults" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Consults_StaffUsers_DoctorId" FOREIGN KEY ("DoctorId") REFERENCES "StaffUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Consults_Visits_VisitId" FOREIGN KEY ("VisitId") REFERENCES "Visits" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_Consults_DoctorId" ON "Consults" ("DoctorId");
CREATE INDEX "IX_Consults_VisitId" ON "Consults" ("VisitId");

CREATE TABLE "Diagnoses" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Details" text NOT NULL,
    "Category" character varying(64),
    "ConsultId" integer NOT NULL,
    CONSTRAINT "PK_Diagnoses" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Diagnoses_Consults_ConsultId" FOREIGN KEY ("ConsultId") REFERENCES "Consults" ("Id") ON DELETE CASCADE
);
CREATE INDEX "IX_Diagnoses_ConsultId" ON "Diagnoses" ("ConsultId");

CREATE TABLE "Referrals" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ReferredFor" text NOT NULL,
    "ReferralNotes" text,
    "ReferralState" character varying(32) NOT NULL,
    "ReferralOutcome" text,
    "ConsultId" integer NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Referrals" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Referrals_Consults_ConsultId" FOREIGN KEY ("ConsultId") REFERENCES "Consults" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_Referrals_ConsultId" ON "Referrals" ("ConsultId");

CREATE TABLE "Orders" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ConsultId" integer NOT NULL,
    "MedicationBrandId" integer NOT NULL,
    "DosageInstructions" text NOT NULL,
    "Remarks" text,
    "Status" character varying(16) NOT NULL,
    "Quantity" integer NOT NULL,
    "ApprovedById" uuid,
    "ApprovedAt" timestamp with time zone,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Orders" PRIMARY KEY ("Id"),
    CONSTRAINT ck_orders_quantity_positive CHECK ("Quantity" > 0),
    CONSTRAINT "FK_Orders_Consults_ConsultId" FOREIGN KEY ("ConsultId") REFERENCES "Consults" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Orders_MedicationBrands_MedicationBrandId" FOREIGN KEY ("MedicationBrandId") REFERENCES "MedicationBrands" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Orders_StaffUsers_ApprovedById" FOREIGN KEY ("ApprovedById") REFERENCES "StaffUsers" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_Orders_ApprovedById" ON "Orders" ("ApprovedById");
CREATE INDEX "IX_Orders_ConsultId" ON "Orders" ("ConsultId");
CREATE INDEX "IX_Orders_MedicationBrandId" ON "Orders" ("MedicationBrandId");
CREATE INDEX "IX_Orders_Status" ON "Orders" ("Status");

CREATE TABLE "Broadcasts" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
